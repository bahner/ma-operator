//! Minimal i18n support for zion.
//!
//! FTL files are fetched on demand from `/i18n/<code>.ftl`, which are served
//! as static assets by Trunk.  This keeps the WASM binary small regardless of
//! how many language files are provided.
//!
//! # Usage
//!
//! ```rust
//! // At startup (before mounting components):
//! i18n::init_from_browser().await;
//!
//! // After config loads, re-apply if user has a preference:
//! if let Some(lang) = cfg.get(".config.ui.language") {
//!     i18n::init(&lang).await;
//! }
//!
//! // Translate a key:
//! let label = t("btn-save");               // → "Save" / "Lagre"
//! let msg   = tf("msg-set", &[("path", ".my.aliases.bob"), ("value", "did:ma:...")]);
//! ```
//!
//! Unknown keys fall back to the key name itself.

use std::cell::RefCell;
use std::collections::HashMap;
use wasm_bindgen::JsCast;
use wasm_bindgen_futures::JsFuture;

thread_local! {
    static MESSAGES: RefCell<HashMap<String, String>> = RefCell::default();
    static CURRENT_LANG: RefCell<String> = RefCell::new("en".into());
}

/// Detect the browser's preferred language and initialise i18n.
///
/// Uses `window.navigator.language`. Falls back to English on any error.
pub async fn init_from_browser() {
    let lang = web_sys::window()
        .map(|w| w.navigator().language().unwrap_or_default())
        .unwrap_or_default();
    init(&lang).await;
}

/// (Re-)initialise i18n for the given BCP-47 language tag.
///
/// Fetches `/i18n/<code>.ftl` via the browser Fetch API.  Tries candidates
/// in order (`lang-Script`, `lang`, then `en`) until one succeeds.
pub async fn init(lang: &str) {
    let candidates = normalize(lang);
    let (code, ftl) = load_ftl(&candidates).await;
    CURRENT_LANG.with(|l| *l.borrow_mut() = code);
    MESSAGES.with(|m| *m.borrow_mut() = parse(&ftl));
}

/// Return the active language code (`"en"`, `"nb"`, …).
#[allow(dead_code)]
pub fn lang() -> String {
    CURRENT_LANG.with(|l| l.borrow().clone())
}

/// Look up a translation key.
///
/// Returns the localised string, or the key name itself when not found.
pub fn t(key: &str) -> String {
    MESSAGES.with(|m| {
        m.borrow()
            .get(key)
            .cloned()
            .unwrap_or_else(|| key.to_string())
    })
}

/// Look up a translation key and substitute variables.
///
/// `vars` is a slice of `("varname", "value")` pairs.
/// Replaces every `{ $varname }` occurrence in the translated string.
pub fn tf(key: &str, vars: &[(&str, &str)]) -> String {
    let mut s = t(key);
    for (var, val) in vars {
        s = s.replace(&format!("{{ ${var} }}"), val);
    }
    s
}

// ── Internal helpers ───────────────────────────────────────────────────────

/// Try each candidate FTL file in order; fall back to English.
///
/// Returns `(code_loaded, ftl_text)`.
async fn load_ftl(candidates: &[String]) -> (String, String) {
    for code in candidates {
        if let Ok(s) = fetch_text(&format!("/i18n/{code}.ftl")).await {
            return (code.clone(), s);
        }
    }
    // Final fallback: English
    let s = fetch_text("/i18n/en.ftl").await.unwrap_or_default();
    ("en".to_string(), s)
}

/// Fetch a text resource from `url` via the browser Fetch API.
async fn fetch_text(url: &str) -> Result<String, String> {
    let window = web_sys::window().ok_or("no window")?;
    let resp_val = JsFuture::from(window.fetch_with_str(url))
        .await
        .map_err(|e| format!("{e:?}"))?;
    let resp: web_sys::Response = resp_val
        .dyn_into()
        .map_err(|_| "response cast failed".to_string())?;
    if !resp.ok() {
        return Err(format!("HTTP {}", resp.status()));
    }
    let text_promise = resp.text().map_err(|e| format!("{e:?}"))?;
    let text_val = JsFuture::from(text_promise)
        .await
        .map_err(|e| format!("{e:?}"))?;
    Ok(text_val.as_string().unwrap_or_default())
}

