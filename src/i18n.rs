/// Normalise a BCP-47 tag to an ordered list of candidate `.ftl` file codes,
/// from most-specific to least-specific.
///
/// Both `-` and `_` are accepted as separators; the *semantic* separator is
/// capitalisation:
///
/// | Pattern | Role | Example |
/// |---------|------|---------|
/// | all-lowercase | language | `zh`, `nb`, `sr` |
/// | Title-case    | script   | `Hans`, `Hant`, `Cyrl`, `Latn` |
/// | ALL-CAPS      | region   | `TW`, `NO`, `GB` |
///
/// A 4-letter all-lowercase part is treated as a lowercased script subtag and
/// is normalised to Title case (`hans` → `Hans`).
/// `no` is mapped to `nb` (Norwegian Bokmål).
///
/// Candidates are ordered from most-specific to least-specific; the final
/// fallback to `en` happens in [`load_ftl`].
///
/// Examples:
/// - `"zh-Hans-TW"` / `"zh_Hans_TW"` → `["zh-Hans-TW", "zh-Hans", "zh"]`
/// - `"sr-Cyrl"` → `["sr-Cyrl", "sr"]`
/// - `"nb-NO"` → `["nb-NO", "nb"]`
/// - `"en-GB"` → `["en-GB", "en"]`
fn normalize(lang: &str) -> Vec<String> {
    // Handle private-use subtags such as `art-x-lyaric` (BCP-47 §2.2.7).
    // These contain `-x-` and must be passed through verbatim since the
    // part-by-part classifier below would mangle them.
    let normalised_input = lang.replace('_', "-").to_lowercase();
    if normalised_input.contains("-x-") {
        return vec![normalised_input];
    }

    let mut language = "en".to_string();
    let mut script: Option<String> = None;
    let mut region: Option<String> = None;

    for part in lang.split(['-', '_']).filter(|s| !s.is_empty()) {
        let first_upper = part.chars().next().map_or(false, char::is_uppercase);
        let all_upper = part
            .chars()
            .all(|c| c.is_ascii_alphabetic() && c.is_uppercase());

        if !first_upper {
            // All-lowercase: language subtag, or lowercased 4-char script tag.
            let lower = part.to_lowercase();
            if lower.len() == 4 && lower.chars().all(char::is_alphabetic) {
                // e.g. "hans" → "Hans"
                let mut cs = lower.chars();
                if let Some(first) = cs.next() {
                    script = Some(first.to_uppercase().collect::<String>() + cs.as_str());
                }
            } else {
                language = match lower.as_str() {
                    "no" => "nb".to_string(),
                    _ => lower,
                };
            }
        } else if all_upper {
            // ALL-CAPS → region subtag: TW, NO, GB, …
            region = Some(part.to_string());
        } else {
            // Starts uppercase, contains lowercase → script subtag: Hans, Cyrl, …
            script = Some(part.to_string());
        }
    }

    let mut candidates = Vec::new();
    match (&script, &region) {
        (Some(s), Some(r)) => {
            candidates.push(format!("{language}-{s}-{r}"));
            candidates.push(format!("{language}-{s}"));
        }
        (Some(s), None) => candidates.push(format!("{language}-{s}")),
        (None, Some(r)) => candidates.push(format!("{language}-{r}")),
        (None, None) => {}
    }
    candidates.push(language);
    candidates
}

/// Parse a subset of FTL: single-line `key = value` entries.
///
/// Ignores blank lines, lines starting with `#` (comments), and
/// continuation lines (those without ` = `).  Only the first occurrence
/// of a key is kept.
fn parse(ftl: &str) -> HashMap<String, String> {
    let mut map = HashMap::new();
    for line in ftl.lines() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some(eq) = line.find(" = ") {
            let key = line[..eq].trim().to_string();
            let value = line[eq + 3..].to_string();
            map.entry(key).or_insert(value);
        }
    }
    map
}
