// ── Session environment (delegated to ma-zscheme) ──────────────────────────

pub fn init_session_env() {
    ma_zscheme::init_session_env();
}
pub fn reset_session_env() {
    ma_zscheme::reset_session_env();
}
pub(crate) fn get_env() -> Env {
    ma_zscheme::get_env()
}

pub(crate) fn has_event_handler() -> bool {
    matches!(get_env().get("on-event"), Some(SchemeVal::Lambda { .. }))
}

/// Invoke the local event entry point with decoded, typed event data.
///
/// Event values are placed in a child environment and referenced by a fixed
/// AST. They are never serialised into or parsed from Scheme source.
pub async fn call_event(
    event: &str,
    args: Vec<SchemeVal>,
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<SchemeVal, String> {
    let env = Env::extend(&get_env());
    env.define("__ma_event_args", SchemeVal::List(args));
    let expr = parser::SchemeExpr::List(vec![
        parser::SchemeExpr::Atom("on-event".to_string()),
        parser::SchemeExpr::Str(event.to_string()),
        parser::SchemeExpr::Atom("__ma_event_args".to_string()),
    ]);
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    ma_zscheme::eval::eval(expr, env, ctx)
        .await
        .map_err(|error| error.to_string())
}

// ── Session-env serialisation ──────────────────────────────────────────────

pub fn dump_env() -> String {
    let env = get_env();
    let mut pairs: Vec<(String, SchemeVal)> = env.own_bindings();
    pairs.sort_by(|(a, _), (b, _)| a.cmp(b));

    let mut lines = vec![
        "; zscheme session — generated by .my.z.scheme.ma!save".to_string(),
        "; Edit with .my.z.scheme.ma!edit  •  Reload with .my.z.scheme.ma!eval".to_string(),
        String::new(),
    ];
    for (name, val) in &pairs {
        if let Some(src) = val_to_define(name, val) {
            lines.push(src);
            lines.push(String::new());
        }
    }
    lines.join("\n")
}

fn val_to_define(name: &str, val: &SchemeVal) -> Option<String> {
    match val {
        SchemeVal::Str(s) => Some(format!("(define {name} {s:?})")),
        SchemeVal::Int(n) => Some(format!("(define {name} {n})")),
        SchemeVal::Float(f) => Some(format!("(define {name} {f})")),
        SchemeVal::Bool(true) => Some(format!("(define {name} #t)")),
        SchemeVal::Bool(false) => Some(format!("(define {name} #f)")),
        SchemeVal::Nil => Some(format!("(define {name} ())")),
        SchemeVal::List(items) => {
            let elems: Vec<String> = items.iter().map(val_to_src).collect();
            Some(format!("(define {name} '({}))", elems.join(" ")))
        }
        SchemeVal::Map(_) => Some(format!("(define {name} {})", val_to_src(val))),
        SchemeVal::Lambda {
            params, rest, body, ..
        } => {
            let param_str = match rest {
                Some(r) if params.is_empty() => format!(". {r}"),
                Some(r) => format!("{} . {r}", params.join(" ")),
                None => params.join(" "),
            };
            let body_fmt = body
                .iter()
                .map(|e| format!("\n  {}", expr_to_src(e)))
                .collect::<String>();
            Some(format!("(define ({name} {param_str}){body_fmt})"))
        }
        _ => None,
    }
}

fn val_to_src(val: &SchemeVal) -> String {
    match val {
        SchemeVal::Str(s) => format!("{s:?}"),
        SchemeVal::Int(n) => n.to_string(),
        SchemeVal::Float(f) => f.to_string(),
        SchemeVal::Bool(true) => "#t".to_string(),
        SchemeVal::Bool(false) => "#f".to_string(),
        SchemeVal::Nil => "()".to_string(),
        SchemeVal::List(items) => format!(
            "({})",
            items.iter().map(val_to_src).collect::<Vec<_>>().join(" ")
        ),
        SchemeVal::Map(map) => {
            let elems = map
                .iter()
                .map(|(key, value)| format!("{key:?} {}", val_to_src(value)))
                .collect::<Vec<_>>()
                .join(" ");
            format!("(make-map {elems})")
        }
        other => other.display(),
    }
}

fn expr_to_src(expr: &parser::SchemeExpr) -> String {
    match expr {
        parser::SchemeExpr::Nil => "()".to_string(),
        parser::SchemeExpr::Str(s) => format!("{s:?}"),
        parser::SchemeExpr::Atom(s) => s.clone(),
        parser::SchemeExpr::List(fs) => format!(
            "({})",
            fs.iter().map(expr_to_src).collect::<Vec<_>>().join(" ")
        ),
    }
}

// ── Command-line expansion ─────────────────────────────────────────────────

pub fn needs_expansion(line: &str) -> bool {
    let line = parser::strip_comments(line);
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for ch in line.chars() {
        if escaped {
            escaped = false;
            continue;
        }
        if ch == '\\' && quote.is_some() {
            escaped = true;
            continue;
        }
        if let Some(q) = quote {
            if ch == q {
                quote = None;
            }
            continue;
        }
        if ch == '"' || ch == '\'' {
            quote = Some(ch);
            continue;
        }
        if ch == '(' {
            return true;
        }
    }
    false
}

pub(crate) fn has_incomplete_expression(line: &str) -> bool {
    let line = parser::strip_comments(line);
    let chars: Vec<char> = line.chars().collect();
    let mut pos = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    while pos < chars.len() {
        let ch = chars[pos];
        if escaped {
            escaped = false;
            pos += 1;
            continue;
        }
        if ch == '\\' && quote.is_some() {
            escaped = true;
            pos += 1;
            continue;
        }
        if let Some(q) = quote {
            if ch == q {
                quote = None;
            }
            pos += 1;
            continue;
        }
        if ch == '"' || ch == '\'' {
            quote = Some(ch);
            pos += 1;
            continue;
        }
        if ch == '(' {
            let Some((end, _)) = find_balanced_paren(&chars, pos) else {
                return true;
            };
            pos = end + 1;
            continue;
        }
        pos += 1;
    }
    false
}

pub async fn expand(
    line: &str,
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<String, String> {
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    let env = get_env();
    let line = parser::strip_comments(line);
    let chars: Vec<char> = line.chars().collect();
    let mut result = String::new();
    let mut pos = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    while pos < chars.len() {
        let ch = chars[pos];
        if escaped {
            result.push(ch);
            escaped = false;
            pos += 1;
            continue;
        }
        if ch == '\\' && quote.is_some() {
            result.push(ch);
            escaped = true;
            pos += 1;
            continue;
        }
        if let Some(q) = quote {
            result.push(ch);
            if ch == q {
                quote = None;
            }
            pos += 1;
            continue;
        }
        if ch == '"' || ch == '\'' {
            quote = Some(ch);
            result.push(ch);
            pos += 1;
            continue;
        }
        if ch == '(' {
            let (end, span) = find_balanced_paren(&chars, pos)
                .ok_or_else(|| format!("unmatched '(' at column {}", pos + 1))?;
            let val = eval_span(&span, env.clone(), ctx.clone()).await?;
            result.push_str(&val.to_splice()?);
            pos = end + 1;
        } else {
            result.push(ch);
            pos += 1;
        }
    }
    Ok(result)
}

/// Split already-expanded shorthand text into words for `call_shorthand`.
///
/// A `"..."` span (escape-aware, `\"` for a literal quote) collapses to one
/// token flagged as quoted; every other run of non-whitespace characters is
/// one unquoted token. Bare `'` has no special meaning here — unlike Scheme
/// source, shorthand words are never parsed, so an apostrophe in ordinary
/// text (e.g. "don't") must not be mistaken for a quote delimiter.
pub(crate) fn split_words(line: &str) -> Vec<(String, bool)> {
    let mut words = Vec::new();
    let mut current = String::new();
    let mut quoted = false;
    let mut in_quotes = false;
    let mut escaped = false;
    let mut has_token = false;

    for ch in line.chars() {
        if escaped {
            current.push(ch);
            escaped = false;
            has_token = true;
            continue;
        }
        if ch == '\\' && in_quotes {
            escaped = true;
            continue;
        }
        if ch == '"' {
            if in_quotes {
                in_quotes = false;
            } else {
                in_quotes = true;
                quoted = true;
            }
            has_token = true;
            continue;
        }
        if in_quotes {
            current.push(ch);
            continue;
        }
        if ch.is_whitespace() {
            if has_token {
                words.push((std::mem::take(&mut current), quoted));
                quoted = false;
                has_token = false;
            }
            continue;
        }
        current.push(ch);
        has_token = true;
    }
    if has_token {
        words.push((current, quoted));
    }
    words
}

/// Convert one word from `split_words` into the literal `SchemeVal` it
/// stands for — never a symbol lookup. A quoted word is always a plain
/// string; an unquoted word gets the same literal recognition `eval_atom`
/// gives real Scheme atoms (numbers, `#t`/`#f`, `nil`/`()`), falling back to
/// a plain string (which also covers `#`-prefixed fragment atoms as-is).
fn shorthand_arg_val(word: String, was_quoted: bool) -> SchemeVal {
    if was_quoted {
        return SchemeVal::Str(word);
    }
    if let Ok(n) = word.parse::<i64>() {
        return SchemeVal::Int(n);
    }
    if let Ok(f) = word.parse::<f64>() {
        return SchemeVal::Float(f);
    }
    match word.as_str() {
        "#t" | "true" => SchemeVal::Bool(true),
        "#f" | "false" => SchemeVal::Bool(false),
        "nil" | "()" => SchemeVal::Nil,
        _ => SchemeVal::Str(word),
    }
}

/// Call a focus-shorthand command directly: `head` is the Scheme function
/// name, `args` the pre-tokenized remaining words (see `split_words`).
///
/// Argument values are placed in a child environment and referenced by a
/// fixed AST, the same trick `call_event` uses — words are never re-parsed
/// or re-serialised as Scheme source, so none of them need quoting to avoid
/// being looked up as a symbol.
pub async fn call_shorthand(
    head: &str,
    args: Vec<(String, bool)>,
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<SchemeVal, String> {
    let env = Env::extend(&get_env());
    let mut call = vec![parser::SchemeExpr::Atom(head.to_string())];
    for (i, (word, was_quoted)) in args.into_iter().enumerate() {
        let name = format!("__ma_arg_{i}");
        env.define(name.clone(), shorthand_arg_val(word, was_quoted));
        call.push(parser::SchemeExpr::Atom(name));
    }
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    ma_zscheme::eval::eval(parser::SchemeExpr::List(call), env, ctx)
        .await
        .map_err(|error| error.to_string())
}

/// Evaluate one complete Scheme expression entered as a terminal line.
///
/// Returns `Ok(None)` when the line contains text beyond the expression, so
/// callers can use normal command-line expansion instead.
pub async fn eval_standalone(
    line: &str,
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<Option<SchemeVal>, String> {
    let tokens = parser::tokenize(line).map_err(|error| error.to_string())?;
    let (expr, next) = parser::parse_expr(&tokens, 0).map_err(|error| error.to_string())?;
    if next != tokens.len() {
        return Ok(None);
    }
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    ma_zscheme::eval::eval(expr, get_env(), ctx)
        .await
        .map(Some)
        .map_err(|error| error.to_string())
}

pub async fn call_content(
    content: &str,
    verb: &str,
    args: &[String],
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<SchemeVal, String> {
    let env = get_env();
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    load_content_into_env(content, env.clone(), ctx.clone()).await?;
    eval_span(&build_call_str(verb, args), env, ctx).await
}

/// Evaluate local Scheme source into the current session environment.
///
/// Callers supply only trusted local profile content. This function never
/// resolves a DID, CID, or other remote source on its own.
pub(crate) async fn load_content(
    content: &str,
    state: &AppState,
    config: RwSignal<EgoConfig>,
) -> Result<(), String> {
    let env = get_env();
    let ctx: Ctx = Rc::new(EvalCtx {
        state: state.clone(),
        config,
    });
    load_content_into_env(content, env, ctx).await
}

async fn load_content_into_env(content: &str, env: Env, ctx: Ctx) -> Result<(), String> {
    let tokens = parser::tokenize(content).map_err(|e| e.to_string())?;
    let mut pos = 0;
    while pos < tokens.len() {
        let (expr, next) = parser::parse_expr(&tokens, pos).map_err(|e| e.to_string())?;
        ma_zscheme::eval::eval(expr, env.clone(), ctx.clone())
            .await
            .map_err(|e| e.to_string())?;
        pos = next;
    }
    Ok(())
}

fn build_call_str(verb: &str, args: &[String]) -> String {
    if args.is_empty() {
        format!("({verb})")
    } else {
        let q: Vec<String> = args.iter().map(|a| format!("{a:?}")).collect();
        format!("({verb} {})", q.join(" "))
    }
}

fn find_balanced_paren(chars: &[char], start: usize) -> Option<(usize, String)> {
    debug_assert_eq!(chars[start], '(');
    let mut depth: usize = 0;
    let mut in_string = false;
    let mut escaped = false;
    for (i, &ch) in chars.iter().enumerate().skip(start) {
        if escaped {
            escaped = false;
            continue;
        }
        if ch == '\\' && in_string {
            escaped = true;
            continue;
        }
        if in_string {
            if ch == '"' {
                in_string = false;
            }
            continue;
        }
        if ch == '"' {
            in_string = true;
            continue;
        }
        if ch == '(' {
            depth += 1;
        } else if ch == ')' {
            depth -= 1;
            if depth == 0 {
                return Some((i, chars[start..=i].iter().collect()));
            }
        }
    }
    None
}

async fn eval_span(span: &str, env: Env, ctx: Ctx) -> Result<SchemeVal, String> {
    let tokens = parser::tokenize(span).map_err(|e| e.to_string())?;
    let (expr, _) = parser::parse_expr(&tokens, 0).map_err(|e| e.to_string())?;
    ma_zscheme::eval::eval(expr, env, ctx)
        .await
        .map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{config::EgoConfig, state::AppState};
    use futures::executor::block_on;
    use leptos::prelude::{Owner, RwSignal};

    #[test]
    fn needs_expansion_ignores_single_quoted_parentheses() {
        assert!(!needs_expansion(
            "make thing '(begin (set-prop! \"name\" \"Lamp\"))'"
        ));
    }

    #[test]
    fn needs_expansion_ignores_double_quoted_parentheses() {
        assert!(!needs_expansion("say \"not (scheme)\""));
    }

    #[test]
    fn needs_expansion_detects_unquoted_parentheses() {
        assert!(needs_expansion(
            "make thing (string-append (#.my.things.lamp))"
        ));
    }

    #[test]
    fn find_balanced_paren_ignores_quoted_parentheses() {
        let chars: Vec<char> = "(display \"(not the end)\") tail".chars().collect();
        let (end, span) = find_balanced_paren(&chars, 0).expect("balanced expression");
        assert_eq!(span, "(display \"(not the end)\")");
        assert_eq!(end, span.len() - 1);
    }

    #[test]
    fn find_balanced_paren_treats_apostrophe_as_scheme_quote_prefix() {
        let chars: Vec<char> = "(begin '(define foo \"bar\")) tail".chars().collect();
        let (end, span) = find_balanced_paren(&chars, 0).expect("balanced expression");
        assert_eq!(span, "(begin '(define foo \"bar\"))");
        assert_eq!(end, span.len() - 1);
    }

    #[test]
    fn find_balanced_paren_does_not_require_closing_apostrophe() {
        let chars: Vec<char> = "(foo' shdkjhj) tail".chars().collect();
        let (end, span) = find_balanced_paren(&chars, 0).expect("balanced expression");
        assert_eq!(span, "(foo' shdkjhj)");
        assert_eq!(end, span.len() - 1);
    }

    #[test]
    fn incomplete_expression_ignores_quoted_parentheses() {
        assert!(!has_incomplete_expression(
            "say \"an (unclosed parenthesis\""
        ));
        assert!(has_incomplete_expression("say (string-append \"open\""));
    }

    #[test]
    fn load_content_defines_local_session_functions() {
        let _owner = Owner::new();
        let state = AppState::new();
        let config = RwSignal::new(EgoConfig::new());
        init_session_env();

        block_on(load_content(
            "(define (avatar-bootstrap) \"ready\")",
            &state,
            config,
        ))
        .expect("local source loads");

        let value = block_on(call_content("", "avatar-bootstrap", &[], &state, config))
            .expect("loaded local function is callable");
        assert!(matches!(value, SchemeVal::Str(ref text) if text == "ready"));
    }

    #[test]
    fn standalone_expression_returns_its_value() {
        let _owner = Owner::new();
        let state = AppState::new();
        let config = RwSignal::new(EgoConfig::new());
        init_session_env();

        let value = block_on(eval_standalone("(+ 20 22)", &state, config))
            .expect("expression evaluates")
            .expect("line is a standalone expression");
        assert!(matches!(value, SchemeVal::Int(42)));

        assert!(block_on(eval_standalone("say (+ 20 22)", &state, config))
            .expect("non-standalone input parses")
            .is_none());
    }

    #[test]
    fn call_event_passes_network_text_as_a_typed_value() {
        let _owner = Owner::new();
        let state = AppState::new();
        let config = RwSignal::new(EgoConfig::new());
        init_session_env();

        block_on(load_content(
            "(define (on-event event args) (car args))",
            &state,
            config,
        ))
        .expect("local source loads");

        let value = block_on(call_event(
            ":print",
            vec![SchemeVal::Str("(error \"must not run\")".to_string())],
            &state,
            config,
        ))
        .expect("event handler is callable");
        assert!(matches!(value, SchemeVal::Str(ref text) if text == "(error \"must not run\")"));
    }
}
